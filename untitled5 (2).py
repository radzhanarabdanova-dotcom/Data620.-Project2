import numpy as np, pandas as pd, networkx as nx
import matplotlib.pyplot as plt
from networkx.algorithms import bipartite

# ratings: which user rated which movie
r = pd.read_csv('ml-100k/u.data', sep='\t', names=['user','item','rating','ts'])
r = r[r.rating >= 4]   # keep only "liked" ratings

# keep only movies with enough likes, so that rare items don't create noise islands
MIN_LIKES = 20
counts = r.item.value_counts()
r = r[r.item.isin(counts[counts >= MIN_LIKES].index)]
print(len(r), "ratings after filtering,", r.item.nunique(), "movies")

genres = ['unknown','Action','Adventure','Animation','Children','Comedy','Crime',
          'Documentary','Drama','Fantasy','FilmNoir','Horror','Musical','Mystery',
          'Romance','SciFi','Thriller','War','Western']
items = pd.read_csv('ml-100k/u.item', sep='|', encoding='latin-1', header=None)
items.columns = ['item','title','date','vdate','url'] + genres
items['year'] = pd.to_datetime(items['date'], errors='coerce').dt.year
items = items.set_index('item')

users_df = pd.read_csv('ml-100k/u.user', sep='|', names=['user','age','gender','occupation','zip']).set_index('user')
print(len(r), "ratings")

# Two-mode graph: nodes of two types, edges only between types
G = nx.Graph()
users  = [('u', u) for u in r.user.unique()]
movies = [('m', m) for m in r.item.unique()]
G.add_nodes_from(users,  bipartite=0)
G.add_nodes_from(movies, bipartite=1)
G.add_edges_from((('u', a), ('m', b)) for a, b in zip(r.user, r.item))
print("Bipartite?", nx.is_bipartite(G))
print("Nodes:", G.number_of_nodes(), " Edges:", G.number_of_edges())

deg = dict(G.degree())

def project(G, nodes):
    """Weighted projection. 'weight' = number of shared neighbors,
    'jaccard' = shared / (union of neighbors), which removes the popularity effect."""
    P = bipartite.weighted_projected_graph(G, nodes)
    for a, b, d in P.edges(data=True):
        d['jaccard'] = d['weight'] / (deg[a] + deg[b] - d['weight'])
    return P

M = project(G, movies)   # movie-movie: linked if rated by the same people
U = project(G, users)    # user-user: linked if they liked the same movies
print("Movie projection:", M.number_of_nodes(), "nodes,", M.number_of_edges(), "edges")
print("User projection: ", U.number_of_nodes(), "nodes,", U.number_of_edges(), "edges")

MIN_SIZE, MAX_SIZE = 3, 40   # what we consider a reasonable island size

def trim_edges(g, thr, attr):
    """Keep only edges with attr >= thr (island method, SNA book ch. 4)."""
    g2 = nx.Graph()
    g2.add_edges_from((a, b, d) for a, b, d in g.edges(data=True) if d[attr] >= thr)
    return g2

def sweep(g, attr, n=15):
    w = np.array([d[attr] for _, _, d in g.edges(data=True)])
    thresholds = np.unique(np.linspace(np.percentile(w, 90), w.max(), n))
    rows = []
    for t in thresholds:
        h = trim_edges(g, t, attr)
        comps = list(nx.connected_components(h))
        isl = [c for c in comps if MIN_SIZE <= len(c) <= MAX_SIZE]
        rows.append((round(t, 3), h.number_of_edges(), max(len(c) for c in comps),
                     len(isl), sum(len(c) for c in isl)))
    return pd.DataFrame(rows, columns=['threshold','edges','largest component',
                                       'islands','nodes in islands'])

def plot_sweep(table, title):
    plt.plot(table['threshold'], table['largest component'], marker='o')
    plt.xlabel('threshold'); plt.ylabel('size of largest component')
    plt.title(title); plt.show()

tab_raw = sweep(M, 'weight')
print(tab_raw)
plot_sweep(tab_raw, 'Movies: how the network breaks into islands as the threshold grows')

tab_m = sweep(M, 'jaccard')
print(tab_m)
plot_sweep(tab_m, 'Movies (Jaccard): largest component vs threshold')

# Pick the threshold with the most nodes inside islands (or set your own)
THR_M = tab_m.sort_values('nodes in islands', ascending=False).iloc[0]['threshold']
print("Movie threshold:", THR_M)

h = trim_edges(M, THR_M, 'jaccard')
isl_m = sorted([c for c in nx.connected_components(h) if MIN_SIZE <= len(c) <= MAX_SIZE],
               key=len, reverse=True)
print("Islands:", len(isl_m))

for k, c in enumerate(isl_m, 1):
    sub = items.loc[[m for _, m in c]]
    top = sub[genres[1:]].mean().sort_values(ascending=False).head(3)
    print(f"\nIsland {k}: {len(c)} movies")
    print("  genres:", ", ".join(f"{g} {v:.0%}" for g, v in top.items()))
    print("  median release year:", int(sub['year'].median()))
    print("  examples:", "; ".join(sub.title.head(5)))

tab_u = sweep(U, 'jaccard')
print(tab_u)
plot_sweep(tab_u, 'Users (Jaccard): largest component vs threshold')

THR_U = tab_u.sort_values('nodes in islands', ascending=False).iloc[0]['threshold']
print("User threshold:", THR_U)

hu = trim_edges(U, THR_U, 'jaccard')
isl_u = sorted([c for c in nx.connected_components(hu) if MIN_SIZE <= len(c) <= MAX_SIZE],
               key=len, reverse=True)
print("Islands:", len(isl_u))

overall = users_df.loc[[u for _, u in users]]
print(f"\nAll users: mean age {overall.age.mean():.1f}, {(overall.gender=='F').mean():.0%} female")

for k, c in enumerate(isl_u, 1):
    sub = users_df.loc[[u for _, u in c]]
    print(f"\nIsland {k}: {len(c)} users")
    print(f"  mean age {sub.age.mean():.1f}, {(sub.gender=='F').mean():.0%} female")
    print("  top occupations:", ", ".join(sub.occupation.value_counts().head(3).index))
    # what these users liked
    liked = r[r.user.isin([u for _, u in c])].item.value_counts().head(5).index
    print("  most-liked movies:", "; ".join(items.loc[liked].title))

k = 0   # index of the island (0 = largest)
H = h.subgraph(isl_m[k])
pos = nx.spring_layout(H, seed=1)
plt.figure(figsize=(9, 7))
nx.draw(H, pos, node_size=120, node_color='tab:blue', edge_color='gray')
labels = {n: items.loc[n[1], 'title'][:22] for n in H.nodes()}
nx.draw_networkx_labels(H, pos, labels, font_size=7)
plt.show()

for k, c in enumerate(isl_m, 1):
    print(k, "median number of likes per movie:", int(np.median([deg[n] for n in c])))

